/**
 * 서명된 사진 응답이 들어가는 서비스워커 캐시.
 *
 * 이것이 있는 이유는 브라우저 캐시가 **토큰까지 포함한 전체 URL**로 키를 잡기 때문이다.
 * 서명 URL이 갱신되면 바이트 하나 바뀌지 않은 사진 전체가 캐시 미스가 되고, 옷장 격자가
 * 통째로 다시 내려온다. 서비스워커는 쿼리를 뗀 경로로 키를 잡을 수 있어(`vite.config.ts`의
 * `runtimeCaching`) 재서명이 네트워크를 타지 않는다.
 *
 * 이름이 두 곳에서 필요해서 여기 산다 — 캐시를 만드는 워커 설정과, 아래 비우는 쪽.
 * 문자열을 양쪽에 적으면 한쪽만 바뀐 순간 로그아웃이 아무것도 비우지 않는다.
 *
 * 이 캐시의 계약이 세 조각이라 그중 둘이 이 파일에 있다 — 이름과 `PHOTO_CORS`.
 * 셋째는 `vite.config.ts`의 `cacheableResponse`이고, 그 설정이 이 파일을 읽어 간다.
 *
 * **이 파일은 아무것도 import하지 않고 브라우저 전역도 타입으로 쓰지 않는다.**
 * `vite.config.ts`가 위 상수를 읽어 가는데, 그 설정은 자기가 정의하는 `@/` 별칭을 스스로
 * 쓸 수 없고 DOM 없는 Node 프로그램으로 검사된다. 아래 `globalThis` 우회가 그 값이다 —
 * 대안은 설정 쪽 `lib`에 DOM을 통째로 여는 것인데, 그러면 Node에서 도는 파일에
 * `document.querySelector()`를 써도 타입 검사가 통과한다.
 */
export const PHOTO_CACHE_NAME = 'wardrobe-photos'

/**
 * 사진을 그리는 **모든** `<img>`가 걸어야 하는 요청 모드. 위 캐시가 이것에 기댄다.
 *
 * 이것이 없는 `<img>`는 no-cors로 나가고 그 응답은 성공이든 400이든 전부 opaque라
 * `status === 0`이다. 그러면 워커가 만료된 서명에 대한 오류를 사진과 구분하지 못한 채
 * 캐시하고, 캐시 키에서 토큰을 떼는 탓에 **재서명해도 같은 오류가 계속 나온다** —
 * 새로고침으로도 못 푸는 상태다. `vite.config.ts`의 `statuses: [200]`이 그 짝이고,
 * 둘 중 하나만 고치면 캐시가 조용히 아무것도 담지 않거나 오류를 담는다.
 *
 * 서명 토큰은 쿼리에 있어 쿠키가 필요 없으므로 `anonymous`로 충분하다. 버킷 응답이
 * `access-control-allow-origin: *`을 준다는 것이 전제이고, `docs/DEPLOY.md`가 그것을
 * 배포 때 확인한다.
 *
 * 값으로 있는 것은 문자열이 두 곳에 적히지 않게 하기 위해서다. 다만 값이 어긋나는 것을
 * 막을 뿐 속성을 통째로 빠뜨리는 것은 못 막아서, 쓰는 쪽마다 테스트가 하나씩 있다.
 */
export const PHOTO_CORS = 'anonymous'

const browser = globalThis as {
  caches?: { delete(name: string): Promise<boolean> }
}

/**
 * 캐시된 사진을 버린다. **절대 던지지 않는다.**
 *
 * 로그아웃의 마지막 줄이고 세션은 그 전에 이미 끝났다. 여기서 던지면 로그아웃된 사람이
 * "로그아웃하지 못했어요"를 보고, 다시 눌러도 지울 세션이 없어 같은 자리에서 막힌다.
 *
 * 기기를 나눠 쓰는 경우를 위한 것이지 남의 사진을 막는 장치가 아니다 — 경로 첫 칸이
 * `user_id`라 다른 계정은 애초에 같은 URL을 요청하지 않는다.
 *
 * **캐시만 지우고 workbox의 나이 기록(`workbox-expiration` IDB)은 건드리지 않는다.**
 * 한 번 지워봤다가 물렀다. 워커가 그 DB 연결을 열어둔 채 닫지 않아(번들에 `close()`가
 * 없다) `deleteDatabase`는 blocked로 대기하고, 반환된 요청을 관측하지 않으면 지워졌는지
 * 아닌지 알 방법이 없다 — 실행되지 않은 것과 성공한 것이 같아 보이는 줄이었다.
 * 남는 것은 지워진 항목의 타임스탬프뿐이고, 그것이 무해한 이유는 대조가 아니라 순서다 —
 * workbox의 만료 검사는 캐시에 실물이 있는지 보지 않고 나이와 개수만 보므로, 유령
 * 타임스탬프는 LRU에서 늘 가장 오래된 쪽이라 새 사진보다 먼저 밀린다.
 */
export async function clearPhotoCache(): Promise<void> {
  try {
    await browser.caches?.delete(PHOTO_CACHE_NAME)
  } catch (error) {
    console.warn('사진 캐시를 비우지 못함:', error)
  }
}
