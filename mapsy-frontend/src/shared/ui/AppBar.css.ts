import { css } from 'styled-system/css'

/**
 * 화면 상단 바의 세로 여백. 바에 무엇이 들어가는지는 화면마다 다르지만 높이는 달라지면
 * 안 된다 — 화면을 오갈 때 바가 움직인다.
 *
 * 패딩이 전부다. 이 바들에 탭 타겟보다 높은 것이 없어서 패딩이 곧 높이고, 안전영역
 * 인셋을 margin이 아니라 padding으로 먹는 것은 바가 칠하는 표면이 상태바 아래까지
 * 닿게 하기 위해서다.
 *
 * **`css.raw`로 두고 호출부에서 `css(appBarBox, …)`로 합친다.** `css.raw`가 아니면
 * Panda가 이 규칙을 아예 내보내지 않고(빌드 타임에 보이는 호출에서만 뽑는다), `cx`가
 * 아니라 병합인 것은 `cx`가 문자열 이어붙이기라 같은 속성의 승자가 출력 순서로 정해지기
 * 때문이다. 병합이 이기는 건 같은 키로 쓴 경우뿐이라, 호출부가 `py`나 `p`로 같은 변을
 * 건드리면 다시 순서 싸움이 된다.
 */
export const appBarBox = css.raw({
  pt: 'calc({spacing.2} + var(--safe-t))',
  pb: '2',
})
